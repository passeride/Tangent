import assert from "node:assert/strict";
import initSqlJs from "sql.js";
import { migrate, readSettings, writeSettings } from "./storage-schema.js";
const SQL = await initSqlJs();
let db = new SQL.Database();
migrate(db);
assert.equal(readSettings(db), null);
const settings = { version: 1, volume: 0.3, theme: 2 };
writeSettings(db, settings);
db.run("INSERT INTO practice_sessions VALUES ('session-1', 'notes', '2026-10-25T12:00:00Z', NULL)");
db.run("INSERT INTO scores VALUES ('score-1','session-1','correct',3,'2026-10-25T12:00:01Z')");
const bytes = db.export();
assert.equal(new TextDecoder().decode(bytes.slice(0, 15)), "SQLite format 3");
db.close();
db = new SQL.Database(bytes);
migrate(db); migrate(db);
assert.deepEqual(readSettings(db), settings);
assert.equal(db.exec("SELECT value FROM scores")[0].values[0][0], 3);
assert.throws(() => db.run("INSERT INTO scores VALUES ('bad','missing','correct',1,'now')"), /FOREIGN KEY/);
assert.equal(db.exec("PRAGMA integrity_check")[0].values[0][0], "ok");
db.run("PRAGMA user_version = 6");
assert.throws(() => migrate(db), /newer Tangent/);
assert.equal(db.exec("SELECT count(*) FROM scores")[0].values[0][0], 1);
assert.deepEqual(readSettings(db), settings);
db.close();
console.log("SQLite passed: migration, portable export/reopen, future scores, foreign keys and newer-version preservation.");
